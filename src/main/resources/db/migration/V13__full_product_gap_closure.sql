CREATE TABLE IF NOT EXISTS phone_verification_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(32) NOT NULL,
    verification_code VARCHAR(16) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_phone_verification_code_phone ON phone_verification_code(phone_number, purpose, consumed);

ALTER TABLE user_distribution_profile ADD COLUMN IF NOT EXISTS phone_number VARCHAR(32);
CREATE UNIQUE INDEX IF NOT EXISTS uk_user_distribution_profile_phone ON user_distribution_profile(phone_number);

