CREATE TABLE IF NOT EXISTS guild_account_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(32) NOT NULL,
    inviter_user_id BIGINT,
    guild_id VARCHAR(64) NOT NULL,
    guild_name VARCHAR(128) NOT NULL,
    guild_invite_code VARCHAR(64) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_guild_account_config_scope ON guild_account_config(product_code, inviter_user_id);
CREATE INDEX IF NOT EXISTS idx_guild_account_config_guild ON guild_account_config(product_code, guild_id);

